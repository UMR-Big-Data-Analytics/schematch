"""Validate the local source catalog and generate the dataset inventory without network access."""
from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import re

import prepare_datasets as preparation
from audit_matchers import publish

PROJECT = Path(__file__).resolve().parents[1]


def inventory(sources):
    rows = []
    for source, entry in sources.items():
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", source):
            raise ValueError(f"Invalid source ID: {source}")
        for field in ("title", "acquisition", "adapter"):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                raise ValueError(f"{source}: missing {field}")
        support = preparation.preparation_support(entry)
        homepage = entry.get("homepage", "")
        if homepage and not homepage.startswith("https://"):
            raise ValueError(f"{source}: homepage must use HTTPS")
        seen = set()
        for download in entry.get("downloads", []):
            path = preparation.checked_path(PROJECT, download["file"])
            key = str(path).casefold()
            if key in seen:
                raise ValueError(f"{source}: duplicate download destination")
            seen.add(key)
            if not download.get("url", "").startswith("https://"):
                raise ValueError(f"{source}: download URL must use HTTPS")
            if not re.fullmatch(r"(?:sha256:[0-9a-f]{64}|md5:[0-9a-f]{32})", download.get("checksum", "")):
                raise ValueError(f"{source}: missing or invalid checksum")
            if "extract_to" in download and download["extract_to"] != ".":
                preparation.checked_path(PROJECT, download["extract_to"])
        rows.append({"source": source, "entry": entry, "support": support})

    counts = Counter(row["support"] for row in rows)
    lines = ["# Schematch dataset inventory", "",
             "Generated by `python tools/audit_dataset_sources.py` from [dataset_sources.json](tools/dataset_sources.json).",
             "See [DATASETS.md](DATASETS.md) for commands, input layouts, release hashes and paper variants.", "",
             f"The catalog contains **{len(rows)} source/recipe IDs**. IDs are not counts of independent datasets or scenarios.", "",
             "| Preparation support | Source/recipe IDs |", "|---|---|"]
    lines += [f"| {support} | {count} |" for support, count in sorted(counts.items())]
    lines += ["", "Download support means a checked download recipe exists; this audit does not contact publishers or download files.",
              "Local conversion requires manually acquired inputs. Generation from local inputs also requires the named raw releases.",
              "Manual preparation entries provide acquisition guidance; they have no direct `prepare <id>` converter.",
              "MusicBrainz and Lahman inputs can instead be used together through the `controlled` recipe.", "",
              "| Source/recipe ID | Dataset or recipe | Support | Adapter | Acquisition / limitations |", "|---|---|---|---|---|"]
    for row in rows:
        entry = row["entry"]
        title = entry["title"]
        if entry.get("homepage"):
            title = f"[{title}]({entry['homepage']})"
        note = entry["acquisition"].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("|", "&#124;").replace("\n", " ")
        lines.append(f"| `{row['source']}` | {title} | {row['support']} | `{entry['adapter']}` | {note} |")
    lines += ["", "## Validation and paper coverage", "",
              "Preparation emits normal CSV/truth inputs and relative-path dataset configuration; it does not mine dependency profiles.",
              "The [preparation validation record](reports/dataset_preparation_validation.json) covers 700 converted/generated scenarios.",
              "The separate [historical compatibility audit](reports/DATASET_COMPATIBILITY.md) covers 111 installed corpora, 384 dataset directories and 9,931 scenarios (9,927 evaluable, four inference-only).",
              "Those include transformed, repeated and self-matching variants; they are not 111 public releases or a new download verification.",
              "Exact paper replication still needs frozen source snapshots, selections, design manifests, annotations and profiles described in DATASETS.md."]
    return "\n".join(lines) + "\n", counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated inventory is stale")
    args = parser.parse_args()
    content, counts = inventory(preparation.catalog())
    publish(PROJECT / "DATASET_INVENTORY.md", content, args.check)
    print(f"Audited {sum(counts.values())} dataset source/recipe IDs: " +
          ", ".join(f"{count} {mode}" for mode, count in sorted(counts.items())) + ". No downloads performed.")


if __name__ == "__main__":
    main()
